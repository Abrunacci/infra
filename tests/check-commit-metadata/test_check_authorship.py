def check(repo: Path, *extra: str, base: str = "main", head: str = "HEAD") -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            *(sys.executable, str(SCRIPT), "--base", base, "--head", head),
            *("--name", NAME, "--email", EMAIL, "--email", NOREPLY),
            *("--blocked-domain", DOMAIN),
            *extra,
        ],
        cwd=repo,
        env=isolated_env(),
        capture_output=True,
        text=True,
        check=False,
    )


def test_clean_commits_pass(branch: Path) -> None:
    commit(branch, "Add a thing\n\nValues generated by the scheduler are kept.")
    commit(branch, "Link the docs at https://docs.example.org")
    result = check(branch)
    assert result.returncode == 0, result.stdout
    assert "2 commit(s) checked" in result.stdout


def test_commits_already_on_the_base_are_not_checked(repo: Path) -> None:
    commit(repo, "Old", author=("Someone Else", "else@example.com"))
    git(repo, "switch", "--quiet", "--create", "feat/x")
    commit(repo, "New")
    assert check(repo).returncode == 0


@pytest.mark.parametrize(
    ("name", "email"),
    [("Someone Else", EMAIL), (NAME, "other@example.com")],
)
def test_another_author_fails_and_names_the_commit(branch: Path, name: str, email: str) -> None:
    sha = commit(branch, "Sneak in", author=(name, email))[:12]
    result = check(branch)
    assert result.returncode == 1
    assert f'commit {sha} "Sneak in"' in result.stdout
    assert f"author is {name} <{email}>" in result.stdout
    assert "--reset-author" in result.stdout


def test_another_committer_fails(branch: Path) -> None:
    # What applying someone's patch leaves: the author kept, the committer changed.
    commit(branch, "Applied", committer=("Bot", "bot@example.com"))
    result = check(branch)
    assert result.returncode == 1
    assert "committer is Bot <bot@example.com>" in result.stdout
    assert "author is" not in result.stdout


def test_email_case_does_not_matter(branch: Path) -> None:
    commit(branch, "Shout", author=(NAME, EMAIL.upper()))
    assert check(branch).returncode == 0


def test_every_accepted_email_passes(branch: Path) -> None:
    commit(branch, "From the web editor", author=(NAME, NOREPLY), committer=GITHUB)
    commit(branch, "From my machine", author=(NAME, EMAIL))
    assert check(branch).returncode == 0


def test_github_as_committer_passes(branch: Path) -> None:
    # "Update branch": a merge of the base, authored by the maintainer, committed by GitHub.
    tip = commit(branch, "Work")
    git(branch, "switch", "--quiet", "main")
    base = commit(branch, "Meanwhile on main")
    git(branch, "switch", "--quiet", "feat/x")
    commit(branch, "Merge branch 'main' into feat/x", committer=GITHUB, parents=(tip, base))
    result = check(branch)
    assert result.returncode == 0, result.stdout
    assert "2 commit(s) checked" in result.stdout


def test_github_as_committer_does_not_vouch_for_another_author(branch: Path) -> None:
    commit(branch, "Suggested", author=("Someone Else", "else@example.com"), committer=GITHUB)
    result = check(branch)
    assert result.returncode == 1
    assert "author is Someone Else" in result.stdout
    assert "committer is" not in result.stdout


