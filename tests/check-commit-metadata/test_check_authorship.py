# Dependabot


def dependabot_commit(repo: Path, message: str = "Bump a from 1 to 2") -> str:
    return commit(repo, message, author=DEPENDABOT, committer=GITHUB)


def test_dependabot_passes_in_its_own_pull_request(branch: Path) -> None:
    dependabot_commit(branch)
    # The maintainer may still push onto Dependabot's branch.
    commit(branch, "Adapt the code to a 2")
    result = check(branch, "--allow-dependabot", "--pr-author", "dependabot[bot]")
    assert result.returncode == 0, result.stdout


@pytest.mark.parametrize(
    "extra",
    [
        # Not allowed at all.
        ("--pr-author", "dependabot[bot]"),
        # Allowed, but someone else opened the pull request: the commit only claims to be the bot's.
        ("--allow-dependabot", "--pr-author", "someone"),
        ("--allow-dependabot",),
    ],
)
def test_dependabot_fails_otherwise(branch: Path, extra: tuple[str, ...]) -> None:
    dependabot_commit(branch)
    result = check(branch, *extra)
    assert result.returncode == 1
    assert "author is dependabot[bot]" in result.stdout


def test_dependabot_messages_are_still_checked(branch: Path) -> None:
    dependabot_commit(branch, f"Bump a\n\nSee https://{DOMAIN}/x")
    result = check(branch, "--allow-dependabot", "--pr-author", "dependabot[bot]")
    assert result.returncode == 1
    assert f"a link to {DOMAIN}" in result.stdout
    assert "author is" not in result.stdout


