# Fetching, as the action does: the commits are not in the caller's checkout.


@pytest.fixture
def remote(branch: Path) -> tuple[Path, str, str]:
    """A repository like GitHub's: the pull request's head is only under refs/pull/1/head."""
    base = git(branch, "rev-parse", "main")
    commit(branch, "First")
    head = commit(branch, "Second", author=("Someone Else", "else@example.com"))
    git(branch, "update-ref", "refs/pull/1/head", head)
    git(branch, "switch", "--quiet", "main")
    git(branch, "branch", "--quiet", "--delete", "--force", "feat/x")
    # What GitHub allows: fetching any reachable commit by its SHA, with a filter.
    git(branch, "config", "uploadpack.allowFilter", "true")
    git(branch, "config", "uploadpack.allowAnySHA1InWant", "true")
    return branch, base, head


def test_fetch_from_checks_commits_the_checkout_lacks(remote: tuple[Path, str, str], tmp_path: Path) -> None:
    repo, base, head = remote
    empty = tmp_path / "workspace"
    empty.mkdir()
    result = check(empty, "--fetch-from", repo.as_uri(), base=base, head=head)
    assert result.returncode == 1, result.stderr
    assert '"Second"' in result.stdout
    assert '"First"' not in result.stdout
    assert "author is Someone Else" in result.stdout


# The action's own step, run with bash as GitHub runs it, with its default inputs.


def run_action(env: dict[str, str]) -> subprocess.CompletedProcess[str]:
    action = yaml.safe_load((ACTION / "action.yml").read_text())
    step = action["runs"]["steps"][0]
    inputs = {name: spec["default"] for name, spec in action["inputs"].items()}
    step_env = {
        "EVENT_NAME": "pull_request",
        "PR_AUTHOR": "Abrunacci",
        "NAME": inputs["name"],
        "EMAILS": inputs["emails"],
        "BLOCKED_DOMAINS": inputs["blocked-domains"],
        "ALLOW_DEPENDABOT": inputs["allow-dependabot"],
        "ALLOW_RENOVATE": inputs["allow-renovate"],
        "FETCH_TOKEN": "",
        "GITHUB_ACTION_PATH": str(ACTION),
        **env,
    }
    return subprocess.run(
        ["bash", "--noprofile", "--norc", "-eo", "pipefail", "-c", step["run"]],
        env=isolated_env(step_env),
        capture_output=True,
        text=True,
        check=False,
    )


def test_action_skips_events_without_a_pull_request() -> None:
    result = run_action({"EVENT_NAME": "push", "PR_BASE": "", "PR_HEAD": "", "REPO_URL": "x"})
    assert result.returncode == 0, result.stderr
    assert "Nothing to check: 'push'" in result.stdout


def test_action_checks_with_its_defaults(remote: tuple[Path, str, str]) -> None:
    repo, base, head = remote
    env = {"PR_BASE": base, "PR_HEAD": head, "REPO_URL": repo.as_uri()}
    result = run_action(env)
    # The defaults name the real maintainer, so the test's Jane Doe is rejected, on both commits.
    assert result.returncode == 1, result.stderr
    assert '"First"' in result.stdout
    assert '"Second"' in result.stdout
    assert "expected Alejandro Brunacci <abrunacci87@gmail.com> or Alejandro" in result.stdout


def test_action_passes_the_maintainer_and_dependabot(branch: Path) -> None:
    base = git(branch, "rev-parse", "main")
    maintainer = ("Alejandro Brunacci", "abrunacci87@gmail.com")
    dependabot_commit(branch)
    head = commit(branch, "Adapt", author=maintainer)
    git(branch, "config", "uploadpack.allowFilter", "true")
    env = {"PR_BASE": base, "PR_HEAD": head, "REPO_URL": branch.as_uri()}
    result = run_action({**env, "PR_AUTHOR": "dependabot[bot]"})
    assert result.returncode == 0, result.stdout + result.stderr
    assert "2 commit(s) checked" in result.stdout
    # The same commits in a pull request someone else opened.
    assert run_action(env).returncode == 1


def test_action_passes_renovate(branch: Path) -> None:
    base = git(branch, "rev-parse", "main")
    head = commit(branch, "chore(deps): update caddy", author=RENOVATE, committer=GITHUB)
    git(branch, "config", "uploadpack.allowFilter", "true")
    env = {"PR_BASE": base, "PR_HEAD": head, "REPO_URL": branch.as_uri()}
    result = run_action({**env, "PR_AUTHOR": "renovate[bot]"})
    assert result.returncode == 0, result.stdout + result.stderr
    assert run_action(env).returncode == 1
