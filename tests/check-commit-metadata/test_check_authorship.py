# Git knows the empty tree without it being stored.
EMPTY_TREE = "4b825dc642cb6eb9a060e54bf8d69288fbee4904"


def isolated_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    # Away from the machine's git config, so no signing or hook runs on the commits under test,
    # and away from a CI run's variables, so the output is the same everywhere.
    env = {k: v for k, v in os.environ.items() if not k.startswith(("GITHUB_", "GIT_"))}
    return {**env, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1", **(extra or {})}


def git(repo: Path, *args: str, stdin: str | None = None, env: dict[str, str] | None = None) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        input=stdin,
        check=True,
        capture_output=True,
        text=True,
        env=isolated_env(env),
    ).stdout.strip()


def commit(
    repo: Path,
    message: str,
    *,
    author: tuple[str, str] = (NAME, EMAIL),
    committer: tuple[str, str] | None = None,
    parents: tuple[str, ...] | None = None,
) -> str:
    """Records an empty commit on the current branch with exactly this message and identity.

    Built with `git commit-tree`, the plumbing command, so the message reaches the repository
    byte for byte, as a push would deliver it.
    """
    committer = committer or author
    identity = {
        "GIT_AUTHOR_NAME": author[0],
        "GIT_AUTHOR_EMAIL": author[1],
        "GIT_COMMITTER_NAME": committer[0],
        "GIT_COMMITTER_EMAIL": committer[1],
    }
    if parents is None:
        has_head = subprocess.run(["git", "-C", str(repo), "rev-parse", "--verify", "-q", "HEAD"], check=False)
        parents = ("HEAD",) if has_head.returncode == 0 else ()
    flags = [flag for parent in parents for flag in ("-p", parent)]
    sha = git(repo, "commit-tree", EMPTY_TREE, *flags, stdin=message, env=identity)
    git(repo, "update-ref", "HEAD", sha)
    return sha


